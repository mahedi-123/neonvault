export const getProductById = (id) => products.find(p => p.id === id);

export const getProductsByCategory = (categoryId) => {
  if (categoryId === 'all') return products;
  return products.filter(p => p.category === categoryId);
};

export const getFeaturedProducts = () => products.filter(p => p.isBestSeller || p.isNew || p.isLimited).slice(0, 8);

export const getNewDrops = () => products.filter(p => p.isNew).slice(0, 6);

export const getLimitedProducts = () => products.filter(p => p.isLimited).slice(0, 6);

export const getBestSellers = () => products.filter(p => p.isBestSeller).slice(0, 6);

export const searchProducts = (query) => {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.shortDescription.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q)
  );
};